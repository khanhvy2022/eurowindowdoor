class TestDocx(RemoveAiMarksBase):
    def test_inspect_ai_creator(self):
        src = self.write("ai.docx", build_docx(ai_creator=True))
        rep = inspect_container(src)
        self.assertTrue(rep.has_ai_metadata)

    def test_inspect_custom_xml(self):
        src = self.write("cx.docx", build_docx(custom_xml=True))
        rep = inspect_container(src)
        self.assertTrue(rep.has_ai_metadata)

    def test_clean_removes_ai(self):
        src = self.write("ai2.docx", build_docx(ai_creator=True, custom_xml=True))
        out = self.tmp / "ai2.cleaned.docx"
        report = clean_file(src, output=out)
        self.assertEqual(report["verification"], "passed")
        import zipfile

        with zipfile.ZipFile(out) as zf:
            names = zf.namelist()
            self.assertNotIn("customXml/item1.xml", names)
            core = zf.read("docProps/core.xml").decode("utf-8")
            self.assertNotIn("Claude", core)
            app = zf.read("docProps/app.xml").decode("utf-8")
            self.assertNotIn("Claude", app)

    def test_clean_keeps_body(self):
        src = self.write("body.docx", build_docx(ai_creator=True))
        out = self.tmp / "body.cleaned.docx"
        clean_file(src, output=out)
        import zipfile

        with zipfile.ZipFile(out) as zf:
            self.assertIn("<w:t>Hello</w:t>", zf.read("word/document.xml").decode("utf-8"))


