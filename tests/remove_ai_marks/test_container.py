class TestDetectFormat(unittest.TestCase):
    def test_detect_by_extension_and_magic(self):
        from pathlib import Path

        cases = [
            ("a.md", b"# hi", "markdown"),
            ("a.html", b"<html></html>", "html"),
            ("a.svg", b"<svg/>", "svg"),
            ("a.pdf", b"%PDF-1.4", "pdf"),
            ("a.docx", b"PK\x03\x04", "docx"),
            ("a.odt", b"PK\x03\x04", "odt"),
            ("a.txt", b"hello", "unknown"),
        ]
        for name, head, expected in cases:
            p = Path(name)
            self.assertEqual(detect_container_format(p, head), expected)


