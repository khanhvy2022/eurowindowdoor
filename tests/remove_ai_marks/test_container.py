class TestMarkdown(RemoveAiMarksBase):
    def test_inspect_ai_generator(self):
        src = self.write("ai.md", build_markdown(ai_generator=True))
        rep = inspect_container(src)
        self.assertTrue(rep.has_ai_metadata)
        self.assertTrue(any("frontmatter key: generator" in f for f in rep.findings))

    def test_inspect_ai_key(self):
        src = self.write("ai2.md", build_markdown(ai_key=True))
        rep = inspect_container(src)
        self.assertTrue(rep.has_ai_metadata)

    def test_inspect_clean(self):
        src = self.write("clean.md", build_markdown())
        rep = inspect_container(src)
        self.assertFalse(rep.has_ai_metadata)

    def test_clean_keeps_title(self):
        src = self.write("keep.md", build_markdown(ai_generator=True))
        out = self.tmp / "keep.cleaned.md"
        clean_file(src, output=out)
        text = out.read_text(encoding="utf-8")
        self.assertIn("title: Test", text)
        self.assertNotIn("generator: Claude", text)
        self.assertNotIn("ai_generated", text)

    def test_clean_verification_passed(self):
        src = self.write("v.md", build_markdown(ai_generator=True, ai_key=True))
        out = self.tmp / "v.cleaned.md"
        report = clean_file(src, output=out)
        self.assertEqual(report["verification"], "passed")
        self.verify_cleaned(report)


